#!/usr/bin/env bash
# restore-page.sh <vault-path> <page> [--at <commit>] [--list] [--over] — bring a page back.
#
# Deleting a page is not a safe operation while the only way back is reading git history by
# hand, so a vault that cannot restore cannot afford to trim: splitting an overgrown page means
# deleting the original, and nobody does that willingly without an undo. This is that undo.
#
# It writes the page into the working tree and stops there. `finish.sh` is the only sanctioned
# commit path — it runs the secret gate, regenerates `index.md` and `brief.md` and logs the
# change — so this script never commits, and prints the `finish.sh --add` line to run next.
#
#   restore-page.sh ~/vault topics/foo.md --list     # every commit that touched it
#   restore-page.sh ~/vault topics/foo.md            # from the last commit that had it
#   restore-page.sh ~/vault topics/foo.md --at d34db3
#
# A page that still exists is not overwritten without `--over`: the common mistake is restoring
# over a page that was rewritten rather than deleted, which loses the rewrite silently.
set -euo pipefail
vp="${1:?usage: restore-page.sh <vault-path> <page> [--at <commit>] [--list] [--over]}"
page="${2:?usage: restore-page.sh <vault-path> <page> [--at <commit>] [--list] [--over]}"
shift 2
at="" list=0 over=0
while [ $# -gt 0 ]; do
  case "$1" in
    --at)   at="${2:?--at needs a commit}"; shift ;;
    --list) list=1 ;;
    --over) over=1 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

cd "$vp"
git rev-parse --git-dir >/dev/null 2>&1 || { echo "not a git checkout: $vp" >&2; exit 1; }
page=${page#./}
case "$page" in
  /*|*..*) echo "page must be a path inside the vault: $page" >&2; exit 2 ;;
  sources/*) echo "sources/ is append-only provenance and is never restored over" >&2; exit 2 ;;
  index.md|brief.md|log.md) echo "$page is generated by finish.sh, not restored" >&2; exit 2 ;;
esac

# --follow so a page that was renamed is still found under its old path.
hist=$(git log --follow --format='%h%x09%cs%x09%s' -- "$page" 2>/dev/null || true)
[ -n "$hist" ] || { echo "no history for $page in $vp" >&2; exit 1; }

if [ "$list" = 1 ]; then
  printf 'commits touching %s, newest first:\n' "$page"
  printf '%s\n' "$hist" | sed 's/^/  /'
  exit 0
fi

if [ -z "$at" ]; then
  # The newest commit where the file is present. The tip may be the deletion itself, and a
  # deletion commit has no blob to read, so walk back until one does.
  while IFS=$'\t' read -r c _ _; do
    if git cat-file -e "$c:$page" 2>/dev/null; then at=$c; break; fi
  done < <(printf '%s\n' "$hist")
  [ -n "$at" ] || { echo "no commit in the history of $page still carries it" >&2; exit 1; }
fi

git cat-file -e "$at:$page" 2>/dev/null || { echo "$page does not exist at $at" >&2; exit 1; }

if [ -e "$page" ] && [ "$over" != 1 ]; then
  echo "$page already exists; pass --over to replace it." >&2
  echo "What is there now may be a rewrite rather than the thing you deleted — diff first:" >&2
  echo "  git -C \"$vp\" diff $at -- \"$page\"" >&2
  exit 1
fi

mkdir -p "$(dirname "$page")"
git show "$at:$page" > "$page"
meta=$(git log -1 --format='%h %cs %s' "$at")
printf 'restored %s from %s\n' "$page" "$meta"
printf 'not committed. Gate and log it with:\n'
printf '  <plugin root>/scripts/finish.sh --vault %s --op ingest --add %s --note "restore %s"\n' \
  "$vp" "$page" "$page"

# A page nothing links to is invisible, and a restore is exactly when that happens: the links
# to it were edited away when it was deleted. Say so rather than leave it to lint rule 3.
stem=${page##*/}; stem=${stem%.md}; dir=${page%/*}
inbound=$(grep -rl -- "\[\[$dir/$stem\]\]" . --include='*.md' 2>/dev/null \
  | grep -v "^\./sources/" | grep -v "^\./$page\$" | head -3 || true)
if [ -z "$inbound" ]; then
  printf 'no page links to [[%s/%s]] — add a link, or lint rule 3 will report it as an orphan.\n' "$dir" "$stem"
fi
