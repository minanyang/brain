#!/usr/bin/env bash
# Regenerate <vault>/index.md from the wiki pages: one line per page —
# [[dir/page]] — first sentence of the page body — grouped by directory.
#
#   index.sh <vault-path>
#
# The first line says the file is generated. index.md is the file a reader meets first and
# so the one most likely to be corrected by hand, where the correction is overwritten here
# without a trace; a page carrying `deprecated:` is marked in front of its summary, because
# the session map quotes these lines and must send the reader to the successor.
set -euo pipefail
vp="${1:?vault path}"
cd "$vp"

summary() { # first non-empty, non-heading line after the frontmatter, cut at the first sentence end
  awk 'BEGIN{fm=0} NR==1 && /^---$/ {fm=1; next} fm==1 && /^---$/ {fm=2; next} fm==2 && !/^\s*$/ && !/^#/ && !/^<!--/ {print; exit}' "$1" \
    | sed -E 's/[[:space:]]+/ /g; s/^ //; s/(\.|。)( |$).*/\1/' | jq -Rr 'if length > 220 then .[0:219] + "…" else . end'   # jq slices by code point, never mid-character
}

{
  printf '<!-- generated by brain (scripts/index.sh) — edits are overwritten; change the page -->\n'
  printf '# Index\n'
  for d in $(find . -maxdepth 1 -mindepth 1 -type d ! -name sources ! -name '.*' | sed 's|^\./||' | sort); do
    pages=$(find "$d" -maxdepth 1 -name '*.md' | sort)
    [ -n "$pages" ] || continue
    printf '\n## %s\n' "$d"
    printf '%s\n' "$pages" | while IFS= read -r f; do
      dep=$(grep -m1 '^deprecated:' "$f" | cut -d' ' -f2- || true)
      case "$dep" in ''|false) dep='' ;; *) dep="(deprecated $dep) " ;; esac
      printf -- '- [[%s]] — %s%s\n' "${f%.md}" "$dep" "$(summary "$f")"
    done
  done
} > index.md
